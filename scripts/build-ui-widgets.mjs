import { build } from 'esbuild';
import { compile } from 'sass';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await build({
    absWorkingDir: root,
    entryPoints: ['client/widget-adapters/searchable-select.js', 'client/widget-adapters/popup-dismissal.js', 'client/widget-adapters/overlays.js', 'client/widget-adapters/modeless-chooser.js', 'client/widget-adapters/prompt-windows.js', 'client/widget-adapters/controls.js', 'client/widget-adapters/modal-stack.js'],
    outdir: 'public/js/widgets',
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    banner: { js: '// Generated by npm run widgets:build. Edit packages/ui-widgets/src or client/widget-adapters.' },
    sourcemap: false,
    legalComments: 'none'
});
const output = path.join(root, 'packages/ui-widgets/dist');
await mkdir(output, { recursive: true });
await writeFile(path.join(output, 'widgets.css'), compile(path.join(root, 'packages/ui-widgets/styles/index.scss'), { style: 'expanded', sourceMap: false }).css + '\n');
const specimenStyles = path.join(root, 'packages/ui-widgets/examples/specimen.scss');
await writeFile(path.join(root, 'packages/ui-widgets/examples/specimen.css'), compile(specimenStyles, { style: 'expanded', sourceMap: false }).css + '\n');
