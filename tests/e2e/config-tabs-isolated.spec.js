const fs = require('node:fs');
const path = require('node:path');
const nunjucks = require('nunjucks');
const { test, expect } = require('@playwright/test');
const root = path.resolve(__dirname, '../..');
const env = new nunjucks.Environment(new nunjucks.FileSystemLoader(path.join(root, 'views')), { autoescape: true });

test('System tabs support keyboard navigation while retaining unsaved form values', async ({ page }) => {
    const errors = [], unexpected = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', async route => {
        const url = new URL(route.request().url());
        if (url.origin !== 'http://config-fixture.test') return route.abort();
        const pathname = decodeURIComponent(url.pathname);
        if (pathname === '/config') return route.fulfill({ contentType: 'text/html', body: env.render('config.njk', { title: 'System', config: { ai: { model: 'Existing' } }, modelOptions: ['Existing'], currentPage: 'config' }) });
        if (pathname.startsWith('/api/')) return route.fulfill({ json: { success: true, workflows: [], presets: {}, pendingLoad: null } });
        const file = path.resolve(root, 'public', `.${pathname}`);
        if (file.startsWith(path.join(root, 'public') + path.sep) && fs.existsSync(file) && fs.statSync(file).isFile()) return route.fulfill({ contentType: pathname.endsWith('.js') ? 'text/javascript' : pathname.endsWith('.css') ? 'text/css' : 'application/octet-stream', body: fs.readFileSync(file) });
        unexpected.push(pathname); return route.abort();
    });
    await page.goto('http://config-fixture.test/config');
    const story = page.locator('[data-config-tab-target="story"]');
    await story.click();
    const interval = page.locator('#tonal-scale-evaluation-interval');
    await interval.fill('7');
    await expect(interval).toHaveCSS('color', 'rgb(255, 255, 255)');
    await expect(interval).toHaveCSS('background-color', 'rgb(15, 23, 42)');
    await story.focus(); await page.keyboard.press('ArrowRight');
    await expect(page.locator('[data-config-tab-target="gameplay"]')).toBeFocused();
    await expect(page.locator('[data-config-tab-panel="gameplay"]')).toBeVisible();
    await page.keyboard.press('ArrowLeft');
    await expect(story).toBeFocused(); await expect(interval).toHaveValue('7');
    await page.locator('[data-config-tab-target="ai"]').click();
    const select = page.locator('#ai-model');
    await expect(select).toHaveCSS('color', 'rgb(255, 255, 255)');
    await expect(select).toHaveCSS('background-color', 'rgb(15, 23, 42)');
    await select.selectOption('__add_new__');
    const modal = page.locator('#addModelModal'), input = page.locator('#newModelName');
    await expect(modal).toBeVisible(); await expect(input).toBeFocused();
    await input.fill('Existing'); await input.press('Enter');
    await expect(page.locator('#addModelError')).toContainText('already in the list');
    await page.keyboard.press('Escape'); await expect(modal).toBeHidden(); await expect(select).toBeFocused();
    await expect(select).toHaveValue('Existing');
    await select.selectOption('__add_new__'); await input.fill('New model'); await input.press('Enter');
    await expect(modal).toBeHidden(); await expect(select).toHaveValue('New model');
    const backend = page.locator('#ai-backend'), key = page.locator('#ai-apiKey'), endpoint = page.locator('#ai-endpoint');
    await key.fill('fixture-secret'); await endpoint.fill('http://fixture.test');
    const reveal = key.locator('..').locator('.toggle-password');
    await reveal.click(); await expect(key).toHaveAttribute('type', 'text'); await expect(reveal).toHaveAttribute('aria-pressed', 'true');
    await reveal.click(); await expect(key).toHaveAttribute('type', 'password'); await expect(key).toHaveValue('fixture-secret');
    await backend.selectOption('codex_cli_bridge'); await expect(key).toBeHidden(); await expect(key).not.toHaveAttribute('required');
    await expect(page.locator('#ai-codex-command')).toHaveAttribute('required', '');
    await page.locator('#ai-codex-sessionMode').selectOption('resume_id'); await expect(page.locator('#ai-codex-sessionId')).toBeVisible(); await expect(page.locator('#ai-codex-sessionId')).toHaveAttribute('required', '');
    await backend.selectOption('openai_compatible'); await expect(key).toBeVisible(); await expect(key).toHaveValue('fixture-secret'); await expect(endpoint).toHaveValue('http://fixture.test');
    const toolsMenu = page.locator('.app-tools-menu'), toolsTrigger = toolsMenu.locator('summary');
    await toolsTrigger.click(); await expect(toolsMenu).toHaveAttribute('open', '');
    await page.keyboard.press('Escape'); await expect(toolsMenu).not.toHaveAttribute('open', ''); await expect(toolsTrigger).toBeFocused();
    await page.setViewportSize({ width: 390, height: 844 });
    const mobileToggle = page.locator('#appHeaderMenuToggle');
    await mobileToggle.click(); await expect(mobileToggle).toHaveAttribute('aria-expanded', 'true');
    await page.keyboard.press('Escape'); await expect(mobileToggle).toHaveAttribute('aria-expanded', 'false'); await expect(mobileToggle).toBeFocused();
    await mobileToggle.click();
    await page.evaluate(() => { const dialog = document.createElement('dialog'); dialog.id = 'fixture-header-dialog'; dialog.innerHTML = '<button>Close fixture</button>'; document.body.append(dialog); dialog.showModal(); });
    await page.keyboard.press('Escape'); await expect(page.locator('#fixture-header-dialog')).not.toHaveAttribute('open', '');
    await expect(mobileToggle).toHaveAttribute('aria-expanded', 'true');
    await page.mouse.click(5, 830); await expect(mobileToggle).toHaveAttribute('aria-expanded', 'false'); await expect(mobileToggle).toBeFocused();
    await page.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pagehide', { persisted: true })));
    await mobileToggle.click(); await expect(mobileToggle).toHaveAttribute('aria-expanded', 'true');
    await page.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pagehide', { persisted: false })));
    await expect(mobileToggle).toHaveAttribute('aria-expanded', 'false');
    await mobileToggle.evaluate(button => button.click()); await expect(mobileToggle).toHaveAttribute('aria-expanded', 'false');
    expect(errors).toEqual([]);
    expect(unexpected.filter(p => !p.startsWith('/assets/'))).toEqual([]);
});

test('System save keeps latest validation eligibility while request is pending', async ({ page }) => {
    const errors = []; let release, attempts = 0;
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', async route => {
        const url = new URL(route.request().url()), pathname = decodeURIComponent(url.pathname);
        if (url.origin !== 'http://config-fixture.test') return route.abort();
        if (pathname === '/config' && route.request().method() === 'POST') { attempts += 1; await new Promise(resolve => { release = resolve; }); return route.fulfill({ json: { success: true, message: 'Saved' } }); }
        if (pathname === '/config') return route.fulfill({ contentType: 'text/html', body: env.render('config.njk', { title: 'System', config: { server: { host: 'localhost', port: 7777 }, ai: { model: 'Existing', backend: 'openai_compatible', endpoint: 'http://fixture.test', apiKey: 'fixture-key' } }, modelOptions: ['Existing'], currentPage: 'config' }) });
        if (pathname.startsWith('/api/')) return route.fulfill({ json: { success: true, workflows: [], presets: {}, pendingLoad: null } });
        const file = path.resolve(root, 'public', `.${pathname}`);
        if (file.startsWith(path.join(root, 'public') + path.sep) && fs.existsSync(file) && fs.statSync(file).isFile()) return route.fulfill({ contentType: pathname.endsWith('.js') ? 'text/javascript' : pathname.endsWith('.css') ? 'text/css' : 'application/octet-stream', body: fs.readFileSync(file) });
        return route.abort();
    });
    await page.goto('http://config-fixture.test/config');
    await page.locator('[data-config-tab-target="server"]').click();
    const button = page.locator('#config-tab-server button[type=submit]');
    await expect(button).toBeEnabled(); const original = await button.textContent();
    await button.click(); await expect.poll(() => attempts).toBe(1); await expect(button).toBeDisabled();
    await page.locator('#server-host').fill('');
    release(); await expect(page.locator('#status-message')).toContainText('Saved');
    await expect(button).toBeDisabled(); await expect(button).toHaveText(original);
    await page.locator('#server-host').fill('localhost'); await expect(button).toBeEnabled();
    expect(errors).toEqual([]);
});
